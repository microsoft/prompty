// Removes the fully generated Java model and example trees before emission.
//
// The Java normalization shim (`normalize-java-output.mjs`) hoists enums into
// their own compilation units and emits small support classes, so the Java
// output directories contain files that the Typra manifest does not track. If a
// model type or enum is removed upstream, nothing else would delete the stale
// file. Clearing the directories first keeps the generated tree a faithful
// projection of the schema.
//
// Only files carrying the generated marker are removed, so a stray hand-written
// file is reported rather than silently deleted.
//
// Extension seams (`<Type>Methods.java`) are the exception. The emitter creates
// them once, only when missing, and never rewrites them, so they are the
// designated home for hand-written `@method` implementations. They deliberately
// carry a seam marker instead of the generated marker; deleting them would
// destroy hand-written code, so they are preserved. They are matched on that
// marker rather than on a file-name pattern, because the emitter's PascalCase
// conversion does not normalise underscores consistently (`foo_bar` -> `FooBar`
// but `foo_1` -> `Foo_1`), which a name pattern would miss.
//
// Several seam markers are accepted. The pinned emitter opens a seam with a
// prose sentence, while later emitter lines front the file with a stable
// machine-readable tag. Because this check is fail-closed, recognising only one
// spelling would abort the build the first time the marker changes -- and the
// failure would be a refusal to clean, not a clear diagnostic.
//
// Pre-accepting a marker the pinned emitter does not yet write does trade away
// some fail-closed strictness, so the exposure is bounded deliberately:
//   * an unrecognised marker still aborts, so genuinely unknown files are never
//     deleted and never silently kept;
//   * generated files open with `MARKER` and are deleted, so the only files this
//     list can preserve are ones already declaring themselves a Typra seam;
//   * tag markers must match the opening line exactly, so a marker cannot be
//     smuggled in as a prefix of unrelated content.
// The residual risk is that a seam-tagged file outlives its `@method`, which is
// the pre-existing orphan case noted below rather than a new one.
//
// Consequence: a seam whose `@method` is later removed from the schema is not
// cleaned up automatically. The Typra manifest does not yet record seam files,
// so orphan detection is left to review.

import { readdirSync, rmSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const MARKER = "// <auto-generated by typra-emitter>";
export const SEAM_MARKER = "// Typra extension seam.";

/**
 * Every accepted opening line for a hand-editable extension seam.
 *
 * `exact` markers must be the whole opening line. The pinned emitter's prose
 * marker is the one exception: its documented form continues with a trailing
 * sentence, so it is necessarily matched as a prefix.
 */
export const SEAM_MARKERS = [
  { marker: SEAM_MARKER, exact: false },
  { marker: "// <typra-extension-seam>", exact: true },
  { marker: "// <typra-editable-seam>", exact: true },
];

/** True when `text` opens with an accepted seam marker. */
export function hasSeamMarker(text) {
  const firstLine = text.split("\n", 1)[0].trimEnd();
  return SEAM_MARKERS.some(({ marker, exact }) =>
    exact ? firstLine === marker : firstLine.startsWith(marker),
  );
}

export const ROOTS = [
  join("..", "runtime", "java", "prompty", "src", "main", "java", "com", "microsoft", "prompty", "model"),
  join("..", "runtime", "java", "prompty", "src", "test", "java", "com", "microsoft", "prompty", "model"),
];

/**
 * Deletes every generated file under `roots`, preserves extension seams, and
 * throws on anything else. Returns the paths that were removed and preserved.
 */
export function cleanJavaOutput(roots = ROOTS) {
  const removed = [];
  const preserved = [];

  for (const root of roots) {
    if (!existsSync(root)) {
      continue;
    }
    for (const name of readdirSync(root)) {
      const path = join(root, name);
      if (!name.endsWith(".java")) {
        throw new Error(`Unexpected non-Java file in generated output directory: ${path}`);
      }
      const text = readFileSync(path, "utf8");
      if (text.startsWith(MARKER)) {
        rmSync(path);
        removed.push(path);
        continue;
      }
      if (hasSeamMarker(text)) {
        preserved.push(path);
        continue;
      }
      throw new Error(
        `Refusing to clean ${path}: it is missing the generated marker. ` +
          "Generated output directories must not contain hand-written files.",
      );
    }
  }

  return { removed, preserved };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  cleanJavaOutput();
}
